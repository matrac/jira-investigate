"""Add or refresh a short index at the top of a growing markdown file. Never removes content.

python md_index.py FILE [--collapse REGEX] [--collapse-label TEXT] [--hint TEXT]

The index lists every `## ` heading (with its `### ` count). Headings whose text matches
--collapse (group 1 = a date or id) are folded into one line: "N <label>, first .. last".
Only the lines between the INDEX markers are ever replaced; every other line stays as it was.
"""
import argparse
import re
import sys
from pathlib import Path

START = "<!-- INDEX:START"
END = "<!-- INDEX:END -->"


def _strip_block(lines):
    out, inside = [], False
    for line in lines:
        if line.startswith(START):
            inside = True
        if not inside:
            out.append(line)
        if line.startswith(END):
            inside = False
    return out


def _build(lines, collapse, label, hint):
    entries, folded, last_topic = [], [], None
    for line in lines:
        text = line.rstrip("\r\n")
        if text.startswith("## "):
            name = text[3:].strip()
            m = collapse.match(name) if collapse else None
            if m:
                folded.append(m.group(1))
                last_topic = None
            else:
                entries.append([name, 0])
                last_topic = entries[-1]
        elif text.startswith("### ") and last_topic is not None:
            last_topic[1] += 1
    block = [f"{START} (generated by md_index.py - refresh it after edits, do not edit by hand) -->",
             f"**Index** - {hint}" if hint else "**Index**"]
    block += [f"- {n} ({k} {'entry' if k == 1 else 'entries'})" if k else f"- {n}" for n, k in entries]
    if folded:
        block.append(f"- {len(folded)} {label}, {folded[0]} .. {folded[-1]}")
    block.append(END)
    return block


def apply_index(text, collapse=None, hint="", label="run logs"):
    eol = "\r\n" if "\r\n" in text else "\n"
    lines = _strip_block(text.splitlines(keepends=True))
    rx = re.compile(collapse) if collapse else None
    block = [b + eol for b in _build(lines, rx, label, hint)]
    at = 1 if lines and lines[0].startswith("# ") else 0
    if at and not lines[0].endswith(("\n", "\r")):
        lines[0] += eol
    return "".join(lines[:at] + block + lines[at:])


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("file")
    ap.add_argument("--collapse")
    ap.add_argument("--collapse-label", default="run logs")
    ap.add_argument("--hint", default="")
    a = ap.parse_args(argv)
    p = Path(a.file)
    with open(p, encoding="utf-8", newline="") as f:
        old = f.read()
    new = apply_index(old, a.collapse, a.hint, a.collapse_label)
    if _strip_block(new.splitlines()) != _strip_block(old.splitlines()):
        sys.exit("refusing to write: content outside the index would change")
    if new != old:
        with open(p, "w", encoding="utf-8", newline="") as f:
            f.write(new)
    print(f"index refreshed: {p}")


if __name__ == "__main__":
    main()
